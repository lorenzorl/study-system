import esbuild from "esbuild";
import process from "node:process";
import { vuePlugin } from "./esbuild-vue-plugin.mjs";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
If you want to view the source, please visit the github repository of this plugin.
*/
`;

const isProduction = process.argv[2] === "production";

const vueFeatureFlags = {
  __VUE_OPTIONS_API__: "true",
  __VUE_PROD_DEVTOOLS__: "false",
  __VUE_PROD_HYDRATION_MISMATCH_DETAILS__: "false",
};

const ctx = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ["src/app/main.ts"],
  bundle: true,
  external: ["obsidian"],
  format: "cjs",
  target: "es2018",
  platform: "browser",
  outfile: "main.js",
  sourcemap: isProduction ? false : "inline",
  // The deck imports Reveal's stylesheets as text and mounts them inside its own
  // shadow root (src/widgets/deck-viewer/ui/DeckViewer.vue), so the plugin's
  // styles.css is never touched. `vite.config.ts` resolves the same two
  // specifiers the same way; the import specifiers must stay identical.
  loader: { ".css": "text" },
  plugins: [vuePlugin()],
  alias: {
    vue: "vue/dist/vue.runtime.esm-bundler.js",
  },
  define: vueFeatureFlags,
});

if (isProduction) {
  await ctx.rebuild();
  await ctx.dispose();
} else {
  await ctx.watch();
}
